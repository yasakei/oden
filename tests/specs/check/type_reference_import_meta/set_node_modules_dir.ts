if (Oden.args.length !== 1) {
  console.error("Usage: set_node_modules_dir.ts <setting>");
  Oden.exit(1);
}
const setting = Oden.args[0].trim();
const odenJson = JSON.parse(Oden.readTextFileSync("./oden.json"));
odenJson["nodeModulesDir"] = setting;
Oden.writeTextFileSync("./oden.json", JSON.stringify(odenJson, null, 2));
